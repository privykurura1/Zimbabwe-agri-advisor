"""Hand-written content shown alongside the model's answer.

Three small JSON files in data/, all edited by people, never generated by the
model at run time:

  local_summaries.json   one short summary per knowledge entry in English, Shona
                         and Ndebele. Only entries marked "reviewed": true are
                         shown, so a half-finished translation never reaches a farmer.
  help_directory.json    who to contact (vet, AGRITEX office, dip tank) by province.
  seasonal_outlook.json  this season's rainfall outlook by Natural Region, copied
                         from the official seasonal forecast.

Audio: audio/<ENTRY>_sn.mp3 (or _nd, _en; .mp3/.ogg/.wav/.m4a) is offered as a
"listen" button when present.
"""
import json
import os
import re

from . import app_dir

ROOT = app_dir()
DATA_DIR = os.path.join(ROOT, "data")
AUDIO_DIR = os.path.join(ROOT, "audio")
LANGS = ("en", "sn", "nd")
AUDIO_TYPES = (".mp3", ".ogg", ".wav", ".m4a")
_ID = re.compile(r"^[A-Z]\d{1,2}$")


def load_json(name, default):
    path = os.path.join(DATA_DIR, name)
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def summaries():
    return load_json("local_summaries.json", {}).get("entries", {})


def audio_for(entry_id, lang):
    """Relative URL of a recorded clip, or None. Entry ids are checked so a
    request can never name a file outside audio/."""
    if not _ID.match(entry_id or "") or lang not in LANGS:
        return None
    for ext in AUDIO_TYPES:
        if os.path.exists(os.path.join(AUDIO_DIR, f"{entry_id}_{lang}{ext}")):
            return f"/audio/{entry_id}_{lang}{ext}"
    return None


def summary_for(entry_ids, language="english"):
    """The first reviewed summary among the matched entries, in the farmer's
    language when available, plus English."""
    lang = {"shona": "sn", "ndebele": "nd"}.get(language, "en")
    table = summaries()
    for entry_id in entry_ids:
        item = table.get(entry_id)
        if not item or not item.get("reviewed"):
            continue
        texts = {k: item.get(k, "").strip() for k in LANGS if item.get(k, "").strip()}
        if not texts:
            continue
        shown = []
        for l in (lang, "en", "sn", "nd"):
            if l in texts and l not in shown:
                shown.append(l)
        return {"entry": entry_id, "title": item.get("title", entry_id),
                "texts": [{"lang": l, "text": texts[l], "audio": audio_for(entry_id, l)} for l in shown],
                "reviewed_by": item.get("reviewed_by", "")}
    return None


def contacts_for(province, domain="animal"):
    """Contacts for a province (falling back to national ones). Entries still
    holding the template placeholder are never shown."""
    directory = load_json("help_directory.json", {})
    wanted = {"animal": {"vet", "dip_tank", "animal_health"}, "crops": {"agritex"}}.get(
        domain, {"vet", "agritex", "dip_tank", "animal_health"})
    found = []
    for place in ([province] if province else []) + ["National"]:
        for c in directory.get("contacts", {}).get(place, []):
            if c.get("type") in wanted and c.get("phone") and "FILL" not in c.get("phone", "") \
                    and "FILL" not in c.get("name", ""):
                found.append({**c, "province": place})
    return found[:4]


def outlook_for(region):
    """This season's outlook for a Natural Region (I-V), if filled in."""
    data = load_json("seasonal_outlook.json", {})
    entry = data.get("regions", {}).get(region or "")
    if not entry or entry.get("outlook") not in {"below normal", "normal", "above normal"}:
        return None
    return {"season": data.get("season", ""), "region": region, "outlook": entry["outlook"],
            "note": entry.get("note", ""), "source": data.get("source", ""),
            "issued": data.get("issued", "")}


_REGION = re.compile(r"\b(?:natural\s+)?region\s*(I{1,3}|IV|V|[1-5])\b|\bNR\s*(I{1,3}|IV|V|[1-5])\b", re.I)
_ROMAN = {"1": "I", "2": "II", "3": "III", "4": "IV", "5": "V"}


def region_in(text):
    """Natural Region named in the farmer's message ("region 4", "NR IV"), or ''."""
    m = _REGION.search(text or "")
    if not m:
        return ""
    value = (m.group(1) or m.group(2)).upper()
    return _ROMAN.get(value, value)


REGION_OF_PROVINCE_NOTE = ("Natural Regions cut across provinces; ask the farmer which region "
                           "their farm is in, or check with the local AGRITEX office.")


PLANTING_ENTRIES = {"A1", "D2"}


def extras_for_answer(entry_ids, language="english", province="", domain="animal", region=""):
    return {"summary": summary_for(entry_ids, language),
            "contacts": contacts_for(province, domain),
            # Rainfall outlook only next to planting / region advice.
            "outlook": outlook_for(region) if region and set(entry_ids) & PLANTING_ENTRIES else None}
